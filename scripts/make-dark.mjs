const NAMED = { white: [255, 255, 255] };
const COLOR = /#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b|rgba?\([^)]*\)|\bwhite\b/g;
function parseColor(tok) {
  if (NAMED[tok]) return { rgb: NAMED[tok] };
  if (tok[0] === '#') {
    let h = tok.slice(1); if (h.length <= 4) h = [...h].map(c => c + c).join('');
    const n = h.match(/../g).map(x => parseInt(x, 16));
    return { rgb: n.slice(0, 3), a: n[3] === undefined ? undefined : n[3] / 255 };
  }
  const m = tok.match(/rgba?\(\s*([\d.]+)[ ,]+([\d.]+)[ ,]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)/);
  if (!m) return null;
  const a = m[4] === undefined ? undefined : m[4].endsWith('%') ? parseFloat(m[4]) / 100 : parseFloat(m[4]);
  return { rgb: [+m[1], +m[2], +m[3]].map(Math.round), a };
}
const kindOf = prop => /^(color|fill|stroke|caret-color|text-decoration-color|-webkit-text-fill-color)$/.test(prop) ? 'text'
  : /^background(-color)?$/.test(prop) ? 'bg' : /^(border|outline)/.test(prop) ? 'border' : null;

function remap(value, kind) {
  if (/gradient|var\(/.test(value)) return value; // not supported: left as is
  return value.replace(COLOR, tok => {
    const c = parseColor(tok); if (!c) return tok;
    // a dark colour with alpha (rgba(0,0,0,.x)) is a shadow/overlay: keep
    return mapColor(c.rgb, c.a, kind) ?? tok;
  });
}

const chain = node => { const parents = []; for (let p = node.parent; p && p.type !== 'root'; p = p.parent) parents.unshift(p); return parents; };
let css = HEADER, rules = 0, decls = 0;
for (const file of FILES) {
  const root = postcss.parse(readFileSync(file, 'utf8'));
  root.walkRules(rule => {
    if (chain(rule).some(p => p.type === 'atrule' && /keyframes/.test(p.name))) return;
    if (/^:root$/.test(rule.selector.trim())) return; // variables are set by hand above
    const changed = [];
    rule.each(d => {
      if (d.type !== 'decl' || d.prop.startsWith('--')) return;
      const kind = kindOf(d.prop); if (!kind) return;
      const v = remap(d.value, kind);
      if (v !== d.value) changed.push(`${d.prop}:${v}${d.important ? '!important' : ''}`);
    });
    if (!changed.length) return;
    let text = `${rule.selector}{${changed.join(';')}}`;
    for (const p of chain(rule).reverse()) text = p.type === 'atrule' ? `@${p.name} ${p.params}{${text}}` : text;
    css += text + '\n'; rules++; decls += changed.length;
  });
}
css += FOOTER;
writeFileSync(OUT, css);
console.log(`dark.css: ${rules} rules, ${decls} colours, ${css.length} bytes`);
