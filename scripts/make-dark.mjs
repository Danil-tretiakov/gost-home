const clamp = (v, a = 0, b = 1) => Math.min(b, Math.max(a, v));
function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  if (!d) return [0, 0, l];
  const s = d / (1 - Math.abs(2 * l - 1));
  const h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [(h * 60 + 360) % 360, s, l];
}
function fromHsl([h, s, l]) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return [r + m, g + m, b + m].map(v => Math.round(clamp(v) * 255));
}
const hex2 = n => n.toString(16).padStart(2, '0');
const out = (rgb, a) => (a === undefined || a >= 1 ? '#' + rgb.map(hex2).join('') : `rgba(${rgb.join(',')},${+a.toFixed(3)})`);

/** kind: text | bg | border. Light colours become dark ones, dark/saturated colours (buttons, accents) stay. */
function mapColor(rgb, a, kind) {
  const [h, s, l] = toHsl(rgb);
  if (kind === 'bg') {
    if (l < 0.55) return null; // already dark or a strong accent
    return out(fromHsl([h, s * 0.55, 0.06 + (1 - l) * 0.34]), a); // white -> #0f0f0e, light greys -> a little lighter
  }
  if (kind === 'border') {
    if (l < 0.55) return null;
    return out(fromHsl([h, s * 0.4, 0.11 + (1 - l) * 0.45]), a);
  }
  // text: dark ink becomes light, tinted dark text (green, red) becomes a lighter tint; light text on colour stays
  if (l > 0.62) return null;
  return out(fromHsl([h, Math.min(1, s * 0.85), clamp(0.93 - l * 0.85, 0.7, 0.95)]), a);
}

